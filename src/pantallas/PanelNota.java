    public void cargarNota(){
        String textoACargar="";
        try(FileReader flujoLectura= new FileReader(nota)){
            textoACargar=flujoLectura.readAllAsString();
        } catch (FileNotFoundException ex) {
            JOptionPane.showMessageDialog(this, "No se ha encontrado la nota","Error",JOptionPane.ERROR_MESSAGE);
        } catch (IOException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(),"Error",JOptionPane.ERROR_MESSAGE);
        }
        campoNotaEscrita.setText(textoACargar);
    }

